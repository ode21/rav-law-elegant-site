// Builds a static copy of the site for plain web hosting (Hostinger / LiteSpeed / Apache).
// Runs the normal build, renders the pages with the built server, and writes everything
// to dist-static/ — upload the *contents* of that folder to public_html.
//
//   node scripts/build-static.mjs
import { spawn, execFileSync } from "node:child_process";
import { cpSync, mkdirSync, rmSync, writeFileSync } from "node:fs";
import { join } from "node:path";

const root = new URL("..", import.meta.url).pathname.replace(/^\/([A-Za-z]:)/, "$1");
const out = join(root, "dist-static");
const port = 4399;

execFileSync(process.execPath, [join(root, "node_modules/vite/bin/vite.js"), "build"], {
  cwd: root,
  stdio: "inherit",
  env: { ...process.env, VERCEL: "", NITRO_PRESET: "node-server" },
});

rmSync(out, { recursive: true, force: true });
mkdirSync(out, { recursive: true });
cpSync(join(root, ".output/public"), out, { recursive: true });

const server = spawn(process.execPath, [join(root, ".output/server/index.mjs")], {
  env: { ...process.env, PORT: String(port) },
  stdio: "ignore",
});

try {
  const base = `http://localhost:${port}`;
  for (let i = 0; ; i++) {
    try {
      await fetch(base);
      break;
    } catch {
      if (i > 50) throw new Error("server did not start");
      await new Promise((r) => setTimeout(r, 200));
    }
  }

  const pages = [
    { path: "/", file: "index.html" },
    { path: "/__not-found__", file: "404.html" },
  ];
  for (const { path, file } of pages) {
    const res = await fetch(base + path);
    writeFileSync(join(out, file), await res.text());
    console.log(`rendered ${path} -> ${file} (${res.status})`);
  }
} finally {
  server.kill();
}

writeFileSync(
  join(out, ".htaccess"),
  `# Generated by scripts/build-static.mjs
Options -Indexes
DirectoryIndex index.html
ErrorDocument 404 /404.html

<IfModule mod_rewrite.c>
  RewriteEngine On
  # Force HTTPS and the bare domain
  RewriteCond %{HTTPS} !=on [OR]
  RewriteCond %{HTTP_HOST} ^www\\. [NC]
  RewriteRule ^ https://ravlawfirm.com%{REQUEST_URI} [L,R=301]
</IfModule>

<IfModule mod_headers.c>
  # JS/CSS/images under /assets have content hashes in their names
  <FilesMatch "-[A-Za-z0-9_-]{8}\\.(js|css|jpg|png|svg|woff2?)$">
    Header set Cache-Control "public, max-age=31536000, immutable"
  </FilesMatch>
  <FilesMatch "\\.html$">
    Header set Cache-Control "no-cache"
  </FilesMatch>
</IfModule>

<IfModule mod_expires.c>
  ExpiresActive On
  ExpiresByType image/jpeg "access plus 1 month"
  ExpiresByType image/png "access plus 1 month"
  ExpiresByType image/x-icon "access plus 1 month"
</IfModule>
`,
);

console.log(`\nStatic site ready in ${out}`);
